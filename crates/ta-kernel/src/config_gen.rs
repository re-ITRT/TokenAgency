/// 一律用双引号 —— 组名里可能有 emoji、`:`、`,`、`#`，在 flow mapping 里
/// 只有显式引号是安全的。
fn q(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 || (c as u32) == 0x7f => {
                let _ = write!(out, "\\u{:04x}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// `["a", "b"]` / `[]`
fn flow_list(items: &[String]) -> String {
    if items.is_empty() {
        return "[]".to_string();
    }
    let inner: Vec<String> = items.iter().map(|s| q(s)).collect();
    format!("[{}]", inner.join(", "))
}

fn scalar_or_plain(s: &str) -> String {
    let t = s.trim();
    if t.is_empty() {
        "warning".to_string()
    } else {
        t.to_string()
    }
}

fn random_secret() -> String {
    use rand::Rng;
    let bytes: [u8; 24] = rand::thread_rng().gen();
    let mut s = String::with_capacity(48);
    for b in bytes {
        let _ = write!(s, "{b:02x}");
    }
    s
}

/// 让 `Path` 参与公共 API（也给调用方一个显式的绝对化工具）
pub fn absolute(path: &Path) -> Result<PathBuf> {
    if path.is_absolute() {
        Ok(path.to_path_buf())
    } else {
        std::env::current_dir()
            .map(|cwd| cwd.join(path))
            .map_err(|e| TaError::Internal(format!("无法取当前目录：{e}")))
    }
}

