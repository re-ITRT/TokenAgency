fn non_blank(s: Option<&str>) -> Option<&str> {
    s.map(str::trim).filter(|s| !s.is_empty())
}

fn is_blank(s: Option<&str>) -> bool {
    non_blank(s).is_none()
}

fn check_regex(re: Option<&str>, path: &str, errors: &mut Vec<FieldError>) {
    let Some(re) = non_blank(re) else { return };
    if let Err(e) = Regex::new(re) {
        errors.push(field_error(path, "invalid_regex", format!("正则不合法（{re:?}）：{e}")));
    }
}

