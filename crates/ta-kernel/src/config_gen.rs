/// `KernelSupervisor::apply()` 从哪里拿"当前期望的配置"。
pub trait KernelConfigSource: Send + Sync {
    /// 渲染 + 原子落盘，返回**绝对路径**（内核 reload 需要绝对路径）
    fn write_generated(&self) -> Result<PathBuf>;
    /// 当前期望的 lane → 内核目标名
    fn lane_targets(&self) -> Result<BTreeMap<LaneId, String>>;
    /// 我们写进配置的 `proxy-providers` key 列表。
    ///
    /// 就绪判定要**逐个**断言它们真的加载到了节点：内核在 provider 为空时
    /// **一边报 error 一边照常启动**，所以只问"进程在不在"会把"整个内核静默降级"报成绿。
    /// 默认空列表 = "没有 provider 需要检查"（全直连的配置）。
    fn expected_providers(&self) -> Result<Vec<String>> {
        Ok(Vec::new())
    }
}

/// `KernelConfigSource` 的默认实现：`MhConfigGen` + 领域配置 + 端口表 → 落盘。
pub struct GeneratedConfigSource {
    gen: Box<dyn KernelConfigGen>,
    doc: RwLock<ConfigDoc>,
    ports: RwLock<PortMap>,
    dir: PathBuf,
    file_name: String,
}

impl GeneratedConfigSource {
    pub fn new(
        gen: Box<dyn KernelConfigGen>,
        doc: ConfigDoc,
        ports: PortMap,
        dir: impl Into<PathBuf>,
    ) -> Self {
        Self {
            gen,
            doc: RwLock::new(doc),
            ports: RwLock::new(ports),
            dir: dir.into(),
            file_name: "kernel.generated.yaml".to_string(),
        }
    }

    pub fn with_file_name(mut self, name: impl Into<String>) -> Self {
        self.file_name = name.into();
        self
    }

    pub fn set_doc(&self, doc: ConfigDoc) {
        *self.doc.write().expect("config source 锁被毒化") = doc;
    }

    pub fn set_ports(&self, ports: PortMap) {
        *self.ports.write().expect("config source 锁被毒化") = ports;
    }

    pub fn path(&self) -> PathBuf {
        self.dir.join(&self.file_name)
    }

    pub fn render(&self) -> Result<String> {
        let doc = self.doc.read().expect("config source 锁被毒化");
        let ports = self.ports.read().expect("config source 锁被毒化");
        self.gen.generate(&doc, &ports)
    }
}

impl KernelConfigSource for GeneratedConfigSource {
    fn write_generated(&self) -> Result<PathBuf> {
        let yaml = self.render()?;
        let path = self.path();
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir)?;
        }
        // 原子写：内核可能正在读旧文件
        let tmp = path.with_extension("yaml.tmp");
        std::fs::write(&tmp, yaml.as_bytes())?;
        std::fs::rename(&tmp, &path)?;
        tracing::debug!(path = %path.display(), bytes = yaml.len(), "内核配置已落盘");
        Ok(path)
    }

    fn lane_targets(&self) -> Result<BTreeMap<LaneId, String>> {
        let doc = self.doc.read().expect("config source 锁被毒化");
        let mut out = BTreeMap::new();
        let mut errors = Vec::new();
        for (i, lane) in doc.lanes.iter().enumerate() {
            match lane_target_at(lane, Some(i)) {
                Ok(t) => {
                    out.insert(lane.id.clone(), t);
                }
                Err(e) => errors.push(e),
            }
        }
        if !errors.is_empty() {
            return Err(TaError::ConfigInvalid { errors });
        }
        Ok(out)
    }

    /// 从**我们已经写出的 YAML** 里读 provider key —— 这样它不可能与生成逻辑漂移，
    /// 而且对任何 [`KernelConfigGen`] 实现都成立（不依赖具体生成器的内部结构）。
    fn expected_providers(&self) -> Result<Vec<String>> {
        let yaml = self.render()?;
        let value: serde_yaml_ng::Value = serde_yaml_ng::from_str(&yaml)
            .map_err(|e| TaError::Internal(format!("回读生成的配置失败：{e}")))?;
        let mut keys: Vec<String> = value
            .get("proxy-providers")
            .and_then(|p| p.as_mapping())
            .map(|m| m.keys().filter_map(|k| k.as_str().map(|s| s.to_string())).collect())
            .unwrap_or_default();
        keys.sort();
        Ok(keys)
    }
}

