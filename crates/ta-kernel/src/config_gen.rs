/// lane 在生成配置里的目标名（组名 / 节点名 / `DIRECT`）。给 `KernelController::set_select` 用。
pub fn lane_target(doc: &ConfigDoc, lane: &Lane) -> Result<String> {
    let index = doc.lanes.iter().position(|l| l.id == lane.id);
    lane_target_at(lane, index).map_err(|e| TaError::ConfigInvalid { errors: vec![e] })
}

/// 同上，但显式给索引（用于生成时报带路径的错）。
pub fn lane_target_at(
    lane: &Lane,
    index: Option<usize>,
) -> std::result::Result<String, FieldError> {
    let path = |f: &str| match index {
        Some(i) => lane_path(i, f),
        None => format!("lanes[?].{f}"),
    };
    match lane.kind {
        LaneKind::Direct => Ok("DIRECT".to_string()),
        // [docs/54] 这个值在 v3 之后是配置损坏：**不落进任何"能用"的分支**，
        // 而是明确报错（否则会拿一个我们不再维护的组名当目标）。
        LaneKind::SubscriptionGroup => Err(field_error(
            &path("kind"),
            "removed_kind",
            "`subscription_group`（用订阅里自带的组）已取消：请改成 `subscription_auto`\
             （「自动选择」）或 `subscription_node`（固定某个节点）",
        )),
        LaneKind::SubscriptionNode => match non_blank(lane.node.as_deref()) {
            Some(n) => Ok(n.to_string()),
            None => {
                Err(field_error(&path("node"), "missing_node", "kind: subscription_node 需要 node"))
            }
        },
        LaneKind::SubscriptionAuto | LaneKind::Filter => Ok(format!("{GROUP_PREFIX}{}", lane.id)),
    }
}

/// 订阅 → 内核 `proxy-providers` key（稳定、只含安全字符）
pub fn provider_key(sub: &Subscription) -> String {
    match non_blank(sub.provider_key.as_deref()) {
        Some(k) => sanitize_key(k),
        None => sanitize_key(sub.id.as_str()),
    }
}

/// 把任意字符串收敛成 YAML key / 文件名安全的形式
pub fn sanitize_key(s: &str) -> String {
    s.trim()
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.') { c } else { '-' })
        .collect()
}

