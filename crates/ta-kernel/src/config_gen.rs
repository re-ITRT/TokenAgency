        let all_ports = [("lane-a", 39100), ("lane-b", 39101)];

        // 默认：遵循 enabled → 停用的 lane 不生成 listener
        let yaml = gen().generate(&doc(y), &ports(&all_ports)).unwrap();
        let ls = parse(&yaml).get("listeners").unwrap().as_sequence().unwrap().clone();
        assert_eq!(ls.len(), 1);
        assert_eq!(ls[0].get("name").unwrap().as_str(), Some("lane-lane-b"));

        // 预览模式：无视 enabled，两条都在
        let yaml2 = gen().with_ignore_enabled(true).generate(&doc(y), &ports(&all_ports)).unwrap();
        let ls2 = parse(&yaml2).get("listeners").unwrap().as_sequence().unwrap().clone();
        assert_eq!(ls2.len(), 2);
        assert_eq!(ls2[0].get("name").unwrap().as_str(), Some("lane-lane-a"));
