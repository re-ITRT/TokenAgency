    #[test]
    fn generated_config_source_writes_atomically() {
        let dir = TempDir::new("gen-source");
        let source = GeneratedConfigSource::new(
            Box::new(gen()),
            doc(WITH_GROUPS),
            ports(&[("lane-direct", 39100), ("lane-jp-auto", 39101), ("lane-us-fixed", 39103)]),
            dir.path(),
        );
        let expected = source.render().unwrap();
        let path = source.write_generated().unwrap();
        assert!(path.is_absolute(), "内核 reload 需要绝对路径：{path:?}");
        assert_eq!(std::fs::read_to_string(&path).unwrap(), expected);
        assert!(!dir.join("kernel.generated.yaml.tmp").exists(), "临时文件应已被 rename");

        // 重复写不报错（覆盖）
        let p2 = source.write_generated().unwrap();
        assert_eq!(p2, path);

        // lane → 内核目标名
        let targets = source.lane_targets().unwrap();
        assert_eq!(targets[&LaneId::new("lane-direct")], "DIRECT");
        assert_eq!(targets[&LaneId::new("lane-jp-auto")], "LANE-lane-jp-auto");

        // 换配置后重新生成
        source.set_doc(doc(ONLY_DIRECT));
        source.set_ports(ports(&[("lane-direct", 39100)]));
        let v = parse(&std::fs::read_to_string(source.write_generated().unwrap()).unwrap());
        assert_eq!(at(&v, "listeners").as_sequence().unwrap().len(), 1);
    }

