use crate::rest::normalize_controller;
use crate::{KernelConfigGen, PortMap};

/// 生成文件的第一行（`docs/11` §2.2）
pub const HEADER: &str = "# GENERATED BY TokenAgency — DO NOT EDIT";
/// 我们自己建的组名前缀
pub const GROUP_PREFIX: &str = "LANE-";
/// 入站监听名前缀
pub const LISTENER_PREFIX: &str = "lane-";
/// 兜底测速 URL（`docs/04` §7.2 建议用真实上游端点，可覆盖）
pub const DEFAULT_HEALTH_URL: &str = "https://www.gstatic.com/generate_204";
/// `interval_s` 为 0 时用 6h
pub const DEFAULT_SUB_INTERVAL_S: u32 = 6 * 3600;

/// 订阅里已知的组名 / 节点名（由 P6 `ta-subscription` 的解析结果提供）。
///
/// 内核自己拉订阅，所以"组名到底存不存在"只有我们手上有清单时才能提前校验。
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct KnownProxies {
    pub groups: Vec<String>,
    pub nodes: Vec<String>,
}

impl KnownProxies {
    pub fn new(groups: Vec<String>, nodes: Vec<String>) -> Self {
        Self { groups, nodes }
    }
    pub fn has_group(&self, name: &str) -> bool {
        self.groups.iter().any(|g| g == name)
    }
    pub fn has_node(&self, name: &str) -> bool {
        self.nodes.iter().any(|n| n == name)
    }
}

/// `KernelConfigGen` 的真实现。
#[derive(Debug, Clone)]
pub struct MhConfigGen {
    secret: String,
    known: BTreeMap<String, KnownProxies>,
    strict_refs: bool,
    ignore_enabled: bool,
    log_level: String,
    default_health_url: String,
}

impl MhConfigGen {
    pub fn new(secret: impl Into<String>) -> Self {
        Self {
            secret: secret.into(),
            known: BTreeMap::new(),
            strict_refs: true,
            ignore_enabled: false,
            log_level: "warning".to_string(),
            default_health_url: DEFAULT_HEALTH_URL.to_string(),
        }
    }

    /// 随机 secret（内核 REST 的 Bearer token）。每次生成新配置都会换，配合 reload/重启使用。
    pub fn random_secret() -> Self {
        Self::new(random_secret())
    }

    pub fn secret(&self) -> &str {
        &self.secret
    }

    pub fn with_secret(mut self, secret: impl Into<String>) -> Self {
        self.secret = secret.into();
        self
    }

    /// 注册某个订阅里已知的组/节点名（key 用 `provider_key`）。
    pub fn with_known_proxies(
        mut self,
        provider_key: impl Into<String>,
        known: KnownProxies,
    ) -> Self {
        self.known.insert(provider_key.into(), known);
        self
    }

    /// `true`（默认）：没有清单时拒绝 `subscription_group` / `subscription_node` 的引用。
    pub fn with_strict_refs(mut self, strict: bool) -> Self {
        self.strict_refs = strict;
        self
    }

    /// `true`：无视 `enabled`，声明的 lane / 订阅全部生成（预览、排查用）。
    /// 默认 `false`，即遵循领域模型的 `enabled`（省略 = 启用）。
    pub fn with_ignore_enabled(mut self, ignore: bool) -> Self {
        self.ignore_enabled = ignore;
        self
    }

    pub fn with_log_level(mut self, level: impl Into<String>) -> Self {
        self.log_level = level.into();
        self
    }

    pub fn with_health_url(mut self, url: impl Into<String>) -> Self {
        self.default_health_url = url.into();
        self
    }

    /// 解析 + 校验，产出可渲染的计划。`generate` 的一半逻辑，单独暴露便于排查。
    pub fn plan<'a>(&self, doc: &'a ConfigDoc, ports: &PortMap) -> Result<Plan<'a>> {
        let mut errors: Vec<FieldError> = Vec::new();

        if doc.net.tun {
            tracing::warn!("net.tun=true 被强制忽略：TokenAgency 绝不接管整机流量");
        }
        if doc.net.system_proxy {
            tracing::warn!("net.system_proxy=true 被强制忽略：TokenAgency 绝不写系统代理");
        }
        if doc.net.dns.enhanced_mode != "redir-host" {
            tracing::warn!(
                mode = %doc.net.dns.enhanced_mode,
                "enhanced-mode 被强制为 redir-host（没有 TUN/DNS 劫持时 fake-ip 无从谈起）"
            );
        }

        let controller = match normalize_controller(&doc.net.kernel.controller) {
            Ok(c) => c,
            Err(e) => {
                errors.push(field_error("net.kernel.controller", "not_loopback", e.to_string()));
                "127.0.0.1:39090".to_string()
            }
        };

        // ---------------- proxy-providers
        let mut index = ProviderIndex::default();
        for (i, sub) in doc.proxy_subscriptions.iter().enumerate() {
            if !self.ignore_enabled && !sub.enabled {
                tracing::debug!(sub_id = %sub.id, "订阅已停用（enabled: false），不生成 proxy-provider");
                index.disabled.insert(sub.id.to_string());
                continue;
            }
            let key = provider_key(sub);
            if key.trim_matches('-').is_empty() {
                errors.push(field_error(
                    &format!("proxy_subscriptions[{i}].id"),
                    "empty_provider_key",
                    format!("订阅 id `{}` 无法派生出内核 provider key", sub.id),
                ));
                continue;
            }
            if sub.url.trim().is_empty() {
                errors.push(field_error(
                    &format!("proxy_subscriptions[{i}].url"),
                    "missing_url",
                    format!("订阅 `{}` 缺少 url", sub.id),
                ));
            }
            check_regex(
                sub.filter.include.as_deref(),
                &format!("proxy_subscriptions[{i}].filter.include"),
                &mut errors,
            );
            check_regex(
                sub.filter.exclude.as_deref(),
                &format!("proxy_subscriptions[{i}].filter.exclude"),
                &mut errors,
            );
            if sub.interval_s == 0 {
                tracing::warn!(sub_id = %sub.id, "订阅 interval 为 0，按 6h 处理");
            }
            if let Some(prev) =
                index.by_key.insert(key.clone(), ProviderPlan { key: key.clone(), index: i, sub })
            {
                errors.push(field_error(
                    &format!("proxy_subscriptions[{i}].provider_key"),
                    "duplicate_provider_key",
                    format!("provider key `{key}` 与 `{}` 冲突", prev.sub.id),
                ));
            }
            index.by_sub_id.insert(sub.id.to_string(), key);
        }

        // ---------------- proxy-groups + listeners
        let mut lanes: Vec<LanePlan<'a>> = Vec::new();
        let mut seen_ids: BTreeMap<String, usize> = BTreeMap::new();
        for (i, lane) in doc.lanes.iter().enumerate() {
            if !self.ignore_enabled && !lane.enabled {
                tracing::debug!(lane_id = %lane.id, "lane 已停用（enabled: false），不生成 listener");
                continue;
            }
            if let Some(prev) = seen_ids.insert(lane.id.to_string(), i) {
                errors.push(field_error(
                    &format!("lanes[{i}].id"),
                    "duplicate_lane_id",
                    format!("lane id `{}` 与 lanes[{prev}] 重复", lane.id),
                ));
            }
            let port = match ports.map.get(&lane.id) {
                Some(p) if *p != 0 => *p,
                Some(_) => {
                    errors.push(field_error(
                        &lane_path(i, "id"),
                        "invalid_port",
                        format!("lane `{}` 的端口为 0", lane.id),
                    ));
                    continue;
                }
                None => {
                    errors.push(field_error(
                        &lane_path(i, "id"),
                        "port_missing",
                        format!(
                            "lane `{}` 还没有分配端口，请先调用 PortAllocator::allocate",
                            lane.id
                        ),
                    ));
                    continue;
                }
            };

            let Some((target, group)) = self.resolve_lane(doc, &index, lane, i, &mut errors) else {
                continue;
            };
            lanes.push(LanePlan { index: i, lane, target, group, port });
        }

        if !errors.is_empty() {
            return Err(TaError::ConfigInvalid { errors });
        }
        Ok(Plan { controller, providers: index.by_key, lanes })
    }

    /// 一条 lane → (`listeners[].proxy`, 需要生成的组)
    fn resolve_lane<'a>(
        &self,
        doc: &'a ConfigDoc,
        index: &ProviderIndex<'a>,
        lane: &'a Lane,
        i: usize,
        errors: &mut Vec<FieldError>,
    ) -> Option<(String, Option<GroupPlan>)> {
        match lane.kind {
            // 直连：不建组
            LaneKind::Direct => Some(("DIRECT".to_string(), None)),

            // 整份订阅里择优 / 筛选后择优：我们建组
            LaneKind::SubscriptionAuto | LaneKind::Filter => {
                let p = self.require_subscription(index, lane, i, errors)?;
                check_regex(lane.filter.as_deref(), &lane_path(i, "filter"), errors);
                check_regex(
                    lane.exclude_filter.as_deref(),
                    &lane_path(i, "exclude_filter"),
                    errors,
                );
                if lane.kind == LaneKind::Filter
                    && is_blank(lane.filter.as_deref())
                    && is_blank(lane.exclude_filter.as_deref())
                {
                    errors.push(field_error(
                        &lane_path(i, "filter"),
                        "missing_filter",
                        "kind: filter 至少要给 filter 或 exclude_filter，否则与 subscription_auto 无区别",
                            ));
                }
                let name = format!("{GROUP_PREFIX}{}", lane.id);
                let group = GroupPlan {
                    name: name.clone(),
                    group_type: lane.group_type.unwrap_or(GroupType::UrlTest),
                    provider_key: p.key.clone(),
                    filter: non_blank(lane.filter.as_deref()).map(str::to_string),
                    // ★ 用户关掉的节点必须从这里排除出去（[docs/54]）—— 见 `merge_disabled_exclude`。
                    exclude_filter: merge_disabled_exclude(
                        lane.exclude_filter.as_deref(),
                        &p.sub.disabled_nodes,
                    ),
                    probe_url: self.lane_probe_url(doc, p.sub),
                    interval_s: lane_health_interval(doc),
                    tolerance_ms: p.sub.health_check.tolerance_ms,
                };
                Some((name, Some(group)))
            }

            // 只按「订阅里的组」这种用法已被取消（[docs/54]，用户第 321 轮："直接放弃订阅里面
            // 分组这一概念，只拿节点"）。v2 → v3 迁移会把老数据转成 `subscription_auto`，
            // 所以走到这里只可能是"迁移没跑到 / 有人手工写回来" —— **明确报错**，
            // 不能落进下面任何一条分支（那会静默按 url-test 建组，出口 IP 自己乱跳）。
            LaneKind::SubscriptionGroup => {
                errors.push(field_error(
                    &lane_path(i, "kind"),
                    "removed_kind",
                    "`subscription_group`（用订阅里自带的组）已取消：请改成 `subscription_auto`\
                     （「自动选择」：所有启用节点 ping 服务商 URL 取最低延迟 + 按地址粘性）\
                     或 `subscription_node`（固定某个节点）",
                ));
                None
            }

            // 固定节点：不建组
            LaneKind::SubscriptionNode => {
                let p = self.require_subscription(index, lane, i, errors)?;
                if !is_blank(lane.filter.as_deref()) || !is_blank(lane.exclude_filter.as_deref()) {
                    tracing::warn!(
                        lane_id = %lane.id,
                        "kind: subscription_node 的 lane 级 filter 被忽略（节点是钉死的）"
                    );
                }
                let name = match non_blank(lane.node.as_deref()) {
                    Some(n) => n.to_string(),
                    None => {
                        errors.push(field_error(
                            &lane_path(i, "node"),
                            "missing_node",
                            "kind: subscription_node 需要 node（订阅里的节点名）",
                        ));
                        return None;
                    }
                };
                self.check_known(&p.key, RefKind::Node, &name, &lane_path(i, "node"), errors);
                Some((name, None))
            }
        }
    }

    fn require_subscription<'b, 'a>(
        &self,
        index: &'b ProviderIndex<'a>,
        lane: &Lane,
        i: usize,
        errors: &mut Vec<FieldError>,
    ) -> Option<&'b ProviderPlan<'a>> {
        let path = lane_path(i, "subscription");
        let Some(sid) = lane.subscription.as_ref().filter(|s| !s.as_str().trim().is_empty()) else {
            errors.push(field_error(
                &path,
                "missing_subscription",
                format!("lane `{}` 的 kind 需要 subscription", lane.id),
            ));
            return None;
        };
        if index.disabled.contains(sid.as_str()) {
            errors.push(field_error(
                &path,
                "subscription_disabled",
                format!("lane `{}` 引用的订阅 `{sid}` 已停用（enabled: false）", lane.id),
            ));
            return None;
        }
        let Some(key) = index.by_sub_id.get(sid.as_str()) else {
            errors.push(field_error(
                &path,
                "subscription_not_found",
                format!("lane `{}` 引用了不存在的订阅 `{sid}`", lane.id),
            ));
            return None;
        };
        match index.by_key.get(key) {
            Some(p) => Some(p),
            None => {
                errors.push(field_error(
                    &path,
                    "subscription_not_found",
                    format!("lane `{}` 引用的订阅 `{sid}` 没有生成 proxy-provider", lane.id),
                ));
                None
            }
        }
    }

    /// ★ 校验"这个组名/节点名在订阅里确实存在"。
    ///
    /// **不是"否则内核会启动失败"**（K4(d) 实测证伪）：内核不校验引用，指向不存在的名字也照样
    /// 绑定成功，只在请求到达时报 502。所以这里是**唯一**能提前拦住它的地方。
    fn check_known(
        &self,
        provider_key: &str,
        kind: RefKind,
        name: &str,
        path: &str,
        errors: &mut Vec<FieldError>,
    ) {
        // [docs/54] 只剩"节点"一种引用要查：`subscription_group` 已取消，
        // 而 `subscription_auto` / `filter` 走的是**我们自己建的组**（名字由 lane id 派生），
        // `direct` 是内核内置。所以这里没有第二种。
        let what = match kind {
            RefKind::Node => "节点",
        };
        match self.known.get(provider_key) {
            Some(known) => {
                let found = match kind {
                    RefKind::Node => known.has_node(name),
                };
                if !found {
                    errors.push(field_error(
                        path,
                        "unknown_reference",
                        format!(
                            "订阅 `{provider_key}` 里没有这个{what}：{name:?}；\
                             listeners[].proxy 指向不存在的名字时**内核不会报错**（照样绑定成功），\
                             只会在请求到达时返回 502 —— 所以在这里拦住"
                        ),
                    ));
                }
            }
            None if self.strict_refs => errors.push(field_error(
                path,
                "unverified_reference",
                format!(
                    "手上没有订阅 `{provider_key}` 的{what}清单，无法确认 {name:?} 存在；\
                     用 MhConfigGen::with_known_proxies 提供（或 with_strict_refs(false) 放行）"
                ),
            )),
            None => tracing::warn!(
                provider_id = %provider_key,
                %name,
                "无法确认{what}存在（没有清单），按不严格模式放行"
            ),
        }
    }

    /// lane 的测速探测 URL：全局覆盖 > 订阅自带 > 默认
    fn lane_probe_url(&self, doc: &ConfigDoc, sub: &Subscription) -> String {
        non_blank(doc.net.health.probe_url.as_deref())
            .or_else(|| non_blank(sub.health_check.url.as_deref()))
            .unwrap_or(&self.default_health_url)
            .to_string()
    }

    fn provider_probe_url(&self, doc: &ConfigDoc, sub: &Subscription) -> String {
        non_blank(sub.health_check.url.as_deref())
            .or_else(|| non_blank(doc.net.health.probe_url.as_deref()))
            .unwrap_or(&self.default_health_url)
            .to_string()
    }
}

impl KernelConfigGen for MhConfigGen {
    fn generate(&self, doc: &ConfigDoc, ports: &PortMap) -> Result<String> {
        let plan = self.plan(doc, ports)?;
        Ok(self.render(doc, &plan))
    }
}

impl MhConfigGen {
    fn render(&self, doc: &ConfigDoc, plan: &Plan<'_>) -> String {
        let mut out = String::new();
        let _ = writeln!(out, "{HEADER}");
        // ---- 隔离项：全部写死，不受配置影响
        let _ = writeln!(out, "mode: rule");
        let _ = writeln!(out, "log-level: {}", scalar_or_plain(&self.log_level));
        let _ = writeln!(out, "mixed-port: 0");
        let _ = writeln!(out, "allow-lan: false");
        let _ = writeln!(out, "bind-address: 127.0.0.1");
        let _ = writeln!(out, "ipv6: false");
        let _ = writeln!(out, "find-process-mode: off");
        let _ = writeln!(out, "external-controller: {}", plan.controller);
        let _ = writeln!(out, "secret: {}", q(&self.secret));
        let _ = writeln!(out, "profile: {{store-selected: true, store-fake-ip: false}}");
        let _ = writeln!(out, "tun: {{enable: false}}");
        let _ = writeln!(out);

        // ---- DNS：redir-host，不用 fake-ip
        let dns = &doc.net.dns;
        let _ = writeln!(out, "dns:");
        let _ = writeln!(out, "  enable: true");
        let _ = writeln!(out, "  enhanced-mode: redir-host");
        let _ = writeln!(out, "  nameserver: {}", flow_list(&dns.nameserver));
        let _ =
            writeln!(out, "  proxy-server-nameserver: {}", flow_list(&dns.proxy_server_nameserver));
        let _ = writeln!(out, "  default-nameserver: {}", flow_list(&dns.default_nameserver));
        let _ = writeln!(out);

        // ---- proxy-providers：每个订阅一个
        if plan.providers.is_empty() {
            let _ = writeln!(out, "proxy-providers: {{}}");
        } else {
            let _ = writeln!(out, "proxy-providers:");
            for p in plan.providers.values() {
                let sub = p.sub;
                let interval =
                    if sub.interval_s == 0 { DEFAULT_SUB_INTERVAL_S } else { sub.interval_s };
                let _ = writeln!(out, "  {}:", p.key);
                let _ = writeln!(out, "    type: http");
                let _ = writeln!(out, "    url: {}", q(&sub.url));
                let _ = writeln!(out, "    interval: {interval}");
                let _ = writeln!(out, "    path: ./providers/{}.yaml", p.key);
                let _ = writeln!(out, "    header:");
                let _ = writeln!(out, "      User-Agent: [{}]", q(&sub.user_agent));
                if let Some(f) = non_blank(sub.filter.include.as_deref()) {
                    let _ = writeln!(out, "    filter: {}", q(f));
                }
                if let Some(f) = non_blank(sub.filter.exclude.as_deref()) {
                    let _ = writeln!(out, "    exclude-filter: {}", q(f));
                }
                let hc = &sub.health_check;
                let _ = writeln!(
                    out,
                    "    health-check: {{enable: {}, url: {}, interval: {}}}",
                    hc.enabled,
                    q(&self.provider_probe_url(doc, sub)),
                    if hc.interval_s == 0 { 60 } else { hc.interval_s }
                );
            }
        }
        let _ = writeln!(out);

        // ---- proxy-groups：我们生成的（不是订阅的）
        let groups: Vec<&GroupPlan> = plan.lanes.iter().filter_map(|l| l.group.as_ref()).collect();
        if groups.is_empty() {
            let _ = writeln!(out, "proxy-groups: []");
        } else {
            let _ = writeln!(out, "proxy-groups:");
            for g in groups {
                let mut fields = vec![
                    format!("name: {}", q(&g.name)),
                    format!("type: {}", group_type_str(g.group_type)),
                    format!("use: [{}]", q(&g.provider_key)),
                    format!("url: {}", q(&g.probe_url)),
                    format!("interval: {}", g.interval_s),
                    format!("tolerance: {}", g.tolerance_ms),
                    // ★ 宁可响亮地失败，也不要静默降级。
                    //
                    // 内核的默认 `empty-fallback` 是 `COMPATIBLE`（= 直连语义）：组里一个节点都没有时
                    // 它会**静默**变成直连，而且**零 error / 零 warning**。两种情况都会踩到：
                    //   1. `filter` 写错、或订阅更新后节点改名 → 筛选结果为空；
                    //   2. 订阅还没拉完 / provider 加载失败 → `use: [provider]` 组为空。
                    // 结果就是"本该走代理的 lane"把用户的境外流量裸奔出去 —— 比报错严重得多。
                    // 显式 `REJECT` 之后，客户端拿到 502、内核日志里能看到 `using G-...-reject[REJECT]`。
                    // 依据：主管 M0 spike 实测（K3）—— filter 匹配不到时默认 `all=[COMPATIBLE]`
                    // 且无任何告警；改成 `REJECT` 后 `all=[REJECT]` 且请求明确失败。
                    "empty-fallback: REJECT".to_string(),
                ];
                if let Some(f) = &g.filter {
                    fields.push(format!("filter: {}", q(f)));
                }
                if let Some(f) = &g.exclude_filter {
                    fields.push(format!("exclude-filter: {}", q(f)));
                }
                let _ = writeln!(out, "  - {{{}}}", fields.join(", "));
            }
        }
        let _ = writeln!(out);

        // ---- listeners：每条 lane 一个 loopback 入站，proxy 指向组/节点/DIRECT
        if plan.lanes.is_empty() {
            let _ = writeln!(out, "listeners: []");
        } else {
            let _ = writeln!(out, "listeners:");
            for l in &plan.lanes {
                let _ = writeln!(
                    out,
                    "  - {{name: {}, type: mixed, listen: 127.0.0.1, port: {}, proxy: {}, udp: false}}",
                    q(&format!("{LISTENER_PREFIX}{}", l.lane.id)),
                    l.port,
                    q(&l.target)
                );
            }
        }
        let _ = writeln!(out);

        // ---- rules：兜底；listeners 已各自指定 proxy，规则不参与决策；
        //      **绝不导入订阅自带的 rules**
        let _ = writeln!(out, "rules:");
        let _ = writeln!(out, "  - MATCH,DIRECT");
        out
    }
}

