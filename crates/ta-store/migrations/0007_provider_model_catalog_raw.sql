-- 0007：目录里的每一行**原样记下上游给的那个模型对象**。
--
-- 背景（用户第 77 轮原话）："模型分为扫描的(自动)\手动添加的，一旦扫描，全部记录下来"。
-- 记的必须是**上游真的给了什么** —— 而 0006 只留了 `(provider_id, upstream_model, suggested_id)`
-- 三样，其中 `suggested_id` 还是**我们派生**的逻辑名。上游原文里的 `object` / `owned_by` /
-- `created` / `permission` / `context_length`（以及中转自己加的任何字段）一个都没留，于是：
--   * 用户看不到上游到底声明了什么（想用别的字段时只能靠猜）；
--   * 给模型填能力字段时**没有可核对的来源** —— 那就只能编，而  写死了
--     "上游没给的字段一个都不编"；
--   * `/v1/models` 要返回**我们的**模型，而目录必须保留上游自己的对象（两者不能混成一份）。
--
-- ★ `raw_json` 存的就是 `GET {base_url}/models` 里**那一条**（`data[i]`）的完整 JSON 对象：
--   不是我们挑出来的字段、不是重新拼的对象。键序也保留（workspace 的 serde_json 开了
--   `preserve_order`），所以"原样"是真的原样，不是"语义等价"。
--
-- ★ 上游那一条不是 JSON 对象（或压根没有）时落 `'{}'`：**绝不补字段**。
--   编一个 `object: "model"` 会让"上游声明过什么"变成我们的猜测 —— 那正是这一轮要禁掉的事。
--
-- ★ `TEXT NOT NULL DEFAULT '{}'`，三条理由：
--   * 文本：人工排查（DB Browser / sqlite3）与 SQLite 的 JSON 函数都直接吃它；
--   * `NOT NULL`：没有第三态 —— "我们没记到原文"就是 `{}`，不用 NULL 冒充
--     "上游给了个空对象"（这两件事在这里本来就是同一件事）；
--   * 默认值：0006 已发布，老库升级上来的行靠它自动得到 `'{}'`，不用写数据回填脚本。
--   （`'{}'` 是常量，SQLite 的 `ALTER TABLE ADD COLUMN` 允许 NOT NULL + 常量默认值。）
--
-- ★ **仍然没有 `origin` 列**：手动添加被用户明确否决（"这样会坏自动化逻辑"），
--   目录里每一行都必须来自一次真实扫描。`migrations.rs` 里那条断言还在钉着它。
--
-- ★ 这列**不参与**任何查询路径（列表/清理/删除都按 `provider_id` + `upstream_model`），
--   所以**不建索引**（0006 顶部那套理由不变：加索引只是让每次 upsert 多维护一棵 B 树）。
--
-- 迁移只增不改：0001–0006 已发布，改它们是灾难。
ALTER TABLE provider_model_catalog ADD COLUMN raw_json TEXT NOT NULL DEFAULT '{}';
