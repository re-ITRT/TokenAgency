//! **真机**验证：启动编排是不是真的把内核拉起来了，以及"绿"是不是只在真就绪时才出现。
//!
//! 为什么要有这个测试（而不是只看 `boot::tests` 里的假内核）：假内核只证明
//! "编排的逻辑对"，证明不了"我们真的 spawn 了一个进程、真的写下了配置、真的等到了 REST 就绪"。
//! 主管要的证据是后者。所以这里用**真的 mihomo 二进制**跑一遍完整路径：
//!
//! ```text
//! build_kernel()      → 真 KernelSupervisor（SystemSpawner + 真 REST 客户端）
//! BootOrchestrator    → apply()：生成 YAML 原子落盘 → spawn mihomo → 轮询 GET /version
//!                     → 内核自己两关都过（REST + provider 判据）→ KernelState::Ready
//! ```
//!
//! 断言的关键两点：
//! 1. **内核真的起来了**：编排观察到的内核状态里出现过 `Ready`，且生成的配置文件真的在磁盘上；
//! 2. **仍然不是绿**：因为网关的装配入口还没接线，编排必须收敛到 `Degraded`
//!    —— 内核就绪不等于应用可用，这个区别不能被糊掉。
//!
//! # 环境依赖与跳过
//!
//! 需要本机有 mihomo 二进制（走 `TA_MIHOMO` 环境变量或 M0 用的默认路径）。
//! **找不到时打印一行明确原因并返回**，不让 `cargo test --workspace` 在没有内核的机器上红
//! （跳过是"如实说没测"，不是"假装通过"）。

use std::path::PathBuf;
use std::sync::{Arc, Mutex};
use std::time::Duration;

use tokenagency_lib::boot::{self, BootPhaseHolder, KernelBootDeps, PhaseSink};
use tokenagency_lib::lifecycle::{BootOrchestrator, BootPhase, StartupArgs};

use ta_core::domain::ConfigDoc;
use ta_kernel::{KernelController, KernelState, KernelStatus};

/// 找 mihomo 二进制：环境变量优先，其次 M0 spike 用过的默认路径。
fn find_mihomo() -> Option<PathBuf> {
    if let Ok(p) = std::env::var("TA_MIHOMO") {
        let p = PathBuf::from(p);
        if p.is_file() {
            return Some(p);
        }
    }
    let known = PathBuf::from(
        r"C:\Users\19404\workspace\.ta-tools\mihomo\mihomo-windows-amd64-compatible.exe",
    );
    if known.is_file() {
        return Some(known);
    }
    None
}

/// 拿一个当前空闲的 TCP 端口（bind 到 0 让系统给，然后立刻放掉给 mihomo 用）。
fn free_port() -> u16 {
    let l = std::net::TcpListener::bind("127.0.0.1:0").expect("bind 临时端口");
    let port = l.local_addr().expect("取本地端口").port();
    drop(l);
    port
}

#[derive(Default)]
struct RecordingSink {
    phases: Mutex<Vec<BootPhase>>,
    kernel_states: Mutex<Vec<KernelState>>,
}

impl PhaseSink for RecordingSink {
    fn phase(&self, phase: BootPhase, _detail: &str) {
        self.phases.lock().unwrap().push(phase);
    }
    fn observe_kernel(&self, status: &KernelStatus) {
        self.kernel_states.lock().unwrap().push(status.state.clone());
    }
}

#[tokio::test(flavor = "multi_thread")]
async fn real_kernel_is_actually_spawned_and_reaches_ready_but_boot_still_degrades() {
    let Some(mihomo) = find_mihomo() else {
        eprintln!(
            "跳过：本机没有 mihomo 二进制（设 TA_MIHOMO 或放到 .ta-tools/mihomo/）—— \
             这条测试需要真内核才能证明\"真的被拉起\""
        );
        return;
    };

    let controller_port = free_port();
    let work = std::env::temp_dir().join(format!("ta-boot-real-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&work);
    std::fs::create_dir_all(&work).expect("建临时目录");

    // 最小可用配置：只要 controller、不要 lane / 订阅。
    // （没有 lane 就不会 bind 任何代理端口；没有 provider，内核的就绪第二关按设计跳过。）
    let mut doc = ConfigDoc::default();
    doc.net.kernel.path = Some(mihomo.to_string_lossy().to_string());
    doc.net.kernel.controller = format!("127.0.0.1:{controller_port}");

    let built =
        boot::build_kernel(&doc, &work).expect("装配不该失败").expect("配了路径就该装配出内核");
    let controller: Arc<dyn KernelController> = built.supervisor.clone();

    let sink = Arc::new(RecordingSink::default());
    let deps = KernelBootDeps::new(Some(controller.clone()), sink.clone());
    let args = StartupArgs::default();

    // 真机就绪通常 1 秒内；给 20 秒余量（冷启动 + 杀软扫描）。
    let outcome = BootOrchestrator::run(&deps, &args, Duration::from_secs(20)).await;

    let observed = sink.kernel_states.lock().unwrap().clone();
    let status = controller.status().await;

    // ---- 证据 1：内核真的被拉起并且真的走到了 Ready
    assert!(
        observed.contains(&KernelState::Ready) || status.state == KernelState::Ready,
        "内核没有就绪。观察到的状态序列：{observed:?}，最终状态：{:?}，last_error={:?}",
        status.state,
        status.last_error
    );
    assert!(status.pid.is_some(), "就绪的内核必须有 pid（说明是真进程）：{status:?}");
    assert!(status.version.is_some(), "就绪的内核必须报出 version（说明 REST 真的通了）");

    // ---- 证据 2：生成的配置真的落盘了（不是纸上谈兵）
    let generated = work.join("kernel").join("kernel.generated.yaml");
    assert!(
        generated.is_file(),
        "生成的内核配置没有落盘：{}（apply() 应该先写配置再拉起）",
        generated.display()
    );
    let yaml = std::fs::read_to_string(&generated).expect("读生成的配置");
    assert!(yaml.contains("GENERATED BY TokenAgency"), "不是我们生成的配置：{yaml}");
    // 隔离项：绝不启用 tun / 系统代理（[09 §1.2] I2）
    assert!(!yaml.contains("0.0.0.0"), "生成的配置里出现了 0.0.0.0：{yaml}");

    // ---- 证据 3：内核就绪 **不等于** 应用可用 —— 网关没接线就必须是 Degraded
    assert_eq!(
        outcome.phase,
        BootPhase::Degraded,
        "网关装配入口还没接线，绝不该报绿。outcome={outcome:?}"
    );
    assert!(
        !sink.phases.lock().unwrap().contains(&BootPhase::Ready),
        "phase 序列里出现了 Ready：{:?}",
        sink.phases.lock().unwrap()
    );
    let detail = outcome.detail.expect("降级必须带可读原因");
    assert!(detail.contains("8787"), "要说清网关没在监听：{detail}");

    // 收尾：杀掉真内核进程，别留孤儿（不给系统留任何东西）
    controller.stop().await.expect("停止内核");
    let _ = std::fs::remove_dir_all(&work);
}

#[test]
fn free_port_and_holder_smoke() {
    // 让上面那条真机测试的辅助函数也被覆盖到（端口探测不能返回 0）
    let p = free_port();
    assert!(p > 1024, "不该拿到特权端口：{p}");

    let holder = BootPhaseHolder::default();
    assert!(!holder.snapshot().is_ready(), "初始状态不该是就绪");
}
